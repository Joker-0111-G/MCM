# 创建地铁网络图
G = nx.Graph()

# 添加所有边（地铁线路连接）
for line in lines:
    color = line["color"]
    stations = line["stations"]
    for i in range(len(stations)-1):
        G.add_edge(stations[i], stations[i+1], color=color, line=line["name"])

# 计算换乘站
station_lines = defaultdict(list)
for line in lines:
    for station in line["stations"]:
        station_lines[station].append(line["name"])

transfer_stations = [station for station, lines in station_lines.items() if len(lines) > 1]

# 生成站台编号
station_labels = {}
for idx, line in enumerate(lines, 1):
    for station_idx, station in enumerate(line["stations"], 1):
        key = f"V{idx},{station_idx}"
        # 如果站名已经在字典中，说明是换乘站，需要生成新的编号
        if station in station_labels:
            station_labels[station].append(key)
        else:
            station_labels[station] = [key]

# 设置可视化参数
plt.figure(figsize=(30, 20))

# 节点颜色（换乘站黄色，普通站浅蓝色）
node_colors = ['yellow' if node in transfer_stations else 'lightblue' for node in G.nodes()]

# 边颜色
edge_colors = [G[u][v]['color'] for u, v in G.edges()]

# 绘制网络
nx.draw(G, pos,
        with_labels=False,  # 不显示原始站名
        node_color=node_colors,
        edge_color=edge_colors,
        node_size=600,
        alpha=0.8)

# 添加自定义标签（编号）
for station, coords in pos.items():
    if station in station_labels:
        # 如果是换乘站，显示所有线路的编号
        labels = station_labels[station]
        label_text = "\n".join(labels)
        plt.text(coords[0], coords[1], label_text, fontsize=13, ha='center', va='center')

# 创建图例
import matplotlib.patches as mpatches
legend_handles = []
for line in lines:
    legend_handles.append(mpatches.Patch(color=line['color'], label=line['name']))
legend_handles.append(mpatches.Patch(color='yellow', label='换乘站'))

plt.legend(handles=legend_handles, loc='upper right')
plt.title("西安地铁线路拓扑图（2025版 - 编号版）", fontsize=20)

